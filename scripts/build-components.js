/**
 * build-components.js
 *
 * Reads all .rs files from components_src/, parses metadata from doc
 * comments, and generates lib/generated-components.ts for the card gallery.
 *
 * WASM compilation + screenshots are handled separately when a C
 * toolchain is available (see CI workflow).
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT, "components_src");
const OUT_TS = path.join(ROOT, "lib", "generated-components.ts");

function slug(name) {
  return name.replace(/\.rs$/, "").replace(/_/g, "-");
}

function parseMeta(source) {
  const lines = source.split("\n");
  const title = (lines[0] || "").replace("//! ", "").trim();
  const desc = (lines[1] || "").replace("//! ", "").trim();
  const tagsLine = lines.find(l => l.startsWith("//! Tags:"));
  const tags = tagsLine ? tagsLine.replace("//! Tags:", "").split(",").map(t => t.trim()).filter(Boolean) : [];
  return { title, description: desc, tags };
}

function collect() {
  return fs.readdirSync(SRC_DIR)
    .filter(f => f.endsWith(".rs"))
    .map(file => {
      const source = fs.readFileSync(path.join(SRC_DIR, file), "utf-8");
      const meta = parseMeta(source);
      return {
        slug: slug(file),
        title: meta.title || slug(file),
        description: meta.description || "",
        tags: meta.tags,
        source,
      };
    });
}

function main() {
  console.log("[build-components] collecting…");
  const items = collect();
  console.log(`  ${items.length} components`);

  const code =
    "// Generated by scripts/build-components.js — do not edit manually\n" +
    "export interface ComponentCard { slug: string; title: string; description: string; tags: string[]; source: string; }\n" +
    `export const componentCards: ComponentCard[] = ${JSON.stringify(items, null, 2)};\n`;

  fs.writeFileSync(OUT_TS, code, "utf-8");
  console.log(`[build-components] done — ${items.length} cards generated`);
}

main();
