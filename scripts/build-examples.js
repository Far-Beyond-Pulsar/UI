/**
 * build-examples.js
 *
 * 1. Reads all .rs files from examples/
 * 2. Generates lib/generated-examples.ts for the code viewer
 * 3. Compiles each example to wasm32-unknown-unknown
 * 4. Runs wasm-bindgen to produce JS + WASM bundles
 * 5. Writes metadata so the page knows which examples have live WASM
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const EXAMPLES_DIR = path.join(ROOT, "examples");
const OUT_TS = path.join(ROOT, "lib", "generated-examples.ts");
const WASM_OUT = path.join(ROOT, "public", "wasm");
const CARGO_TARGET_DIR = path.join(ROOT, "target");

// ── Helpers ──────────────────────────────────────────────────────────────────

function slug(name) {
  return name.replace(/\.rs$/, "").replace(/_/g, "-");
}
function title(name) {
  return name
    .replace(/\.rs$/, "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}
function parseDescription(source) {
  const lines = source.split("\n");
  const docs = [];
  let inBlock = false;
  for (const line of lines) {
    const t = line.trim();
    if (t.startsWith("//!")) {
      inBlock = true;
      const text = t.replace("//!", "").trim();
      if (text && !text.startsWith("!")) docs.push(text);
    } else if (inBlock) break;
  }
  return docs.join(" ");
}

// ── Step 1: collect sources + write TS module ───────────────────────────────

function collectSources() {
  const files = fs
    .readdirSync(EXAMPLES_DIR)
    .filter((f) => f.endsWith(".rs") && f !== "mod.rs");

  return files.map((file) => {
    const source = fs.readFileSync(path.join(EXAMPLES_DIR, file), "utf-8");
    return { slug: slug(file), title: title(file), description: parseDescription(source) || `${title(file)} example`, file, source };
  });
}

function writeTsModule(items) {
  const code = [
    "// Generated by scripts/build-examples.js — do not edit manually",
    "export interface Example { slug: string; title: string; description: string; source: string; }",
    `export const examples: Example[] = ${JSON.stringify(items, null, 2)};`,
  ].join("\n");
  fs.writeFileSync(OUT_TS, code, "utf-8");
}

// ── Step 2: HTML shell generation ────────────────────────────────────────────

function writeHtmlShell(outDir, slug) {
  const wasmName = `example_${slug.replace(/-/g, "_")}`;
  const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    html, body { width: 100%; height: 100%; overflow: hidden; background: #000; }
  </style>
</head>
<body>
  <script src="${wasmName}.js"></script>
  <script>
    wasm_bindgen("./${wasmName}_bg.wasm").catch(function(e) {
      document.body.innerHTML = '<div style="color:#ef4444;padding:2rem;font-family:monospace;font-size:14px">Failed: ' + e.message + '</div>';
    });
  </script>
</body>
</html>`;
  fs.writeFileSync(path.join(outDir, "index.html"), html, "utf-8");
}

// ── Step 3: compile all examples to WASM via a single workspace ──────────────

function compileWasm(items) {
  const meta = {};
  const workspaceDir = path.join(WASM_OUT, ".workspace");

  // Create workspace structure
  const workspaceMembers = [];
  for (const ex of items) {
    const outDir = path.join(WASM_OUT, ex.slug);
    fs.mkdirSync(path.join(outDir), { recursive: true });

    const crateDir = path.join(workspaceDir, ex.slug);
    fs.mkdirSync(path.join(crateDir, "src"), { recursive: true });

    // — lib.rs wrapper — strip inner doc comments (//!) since
    // they conflict when placed in a non-root module
    let cleaned = ex.source.replace(/^\/\/!.*$/gm, "").replace(/\n{3,}/g, "\n\n");
    // Inject logger init at the top of main()
    let body = cleaned.replace(
      /^pub fn main\(\s*\)\s*\{/m,
      '#[wasm_bindgen(start)]\npub fn main() {\n    #[cfg(target_arch = "wasm32")] { console_log::init_with_level(log::Level::Debug).ok(); log::info!("example started"); }');
    let wrapped = 'use wasm_bindgen::prelude::*;\n\n' + body;
    fs.writeFileSync(path.join(crateDir, "src", "lib.rs"), wrapped, "utf-8");
    workspaceMembers.push(ex.slug);
  }

  // — Workspace Cargo.toml —
  const memberLines = workspaceMembers.map((s) => `  "${s}"`).join(",\n");
  fs.writeFileSync(
    path.join(workspaceDir, "Cargo.toml"),
    [
      "[workspace]",
      `members = [\n${memberLines},\n]`,
      "",
      "[workspace.dependencies]",
      'gpui-ce = { path = "D:/GitHub/WGPUI" }',
      'wasm-bindgen = "0.2"',
      'console_log = "1.0"',
      'log = "0.4"',
    ].join("\n"),
    "utf-8",
  );

  // Write individual crate Cargo.tomls
  for (const ex of items) {
    fs.writeFileSync(
      path.join(workspaceDir, ex.slug, "Cargo.toml"),
      [
        `[package]`,
        `name = "example-${ex.slug}"`,
        'version = "0.1.0"',
        'edition = "2021"',
        "",
        "[lib]",
        'crate-type = ["cdylib"]',
        "",
        "[dependencies]",
        "gpui-ce.workspace = true",
        "wasm-bindgen.workspace = true",
        "console_log.workspace = true",
        "log.workspace = true",
      ].join("\n"),
      "utf-8",
    );
  }

  // — Compile all —
  console.log(`  building workspace (${items.length} crates)…`);
  try {
    const output = execSync(
      `cargo build --target wasm32-unknown-unknown --release`,
      { cwd: workspaceDir, env: { ...process.env, CARGO_TARGET_DIR }, stdio: "pipe", timeout: 600000 }
    );

    // All succeeded — run wasm-bindgen for each
    for (const ex of items) {
      const outDir = path.join(WASM_OUT, ex.slug);
      const wasmName = `example_${ex.slug.replace(/-/g, "_")}`;
      const wasmPath = path.join(CARGO_TARGET_DIR, "wasm32-unknown-unknown", "release", `${wasmName}.wasm`);

      if (fs.existsSync(wasmPath)) {
        execSync(`wasm-bindgen --out-dir "${outDir}" --target no-modules --no-typescript "${wasmPath}" 2>&1`, { stdio: "pipe", timeout: 30000 });
        writeHtmlShell(outDir, ex.slug);
        meta[ex.slug] = { ok: true };
        fs.writeFileSync(path.join(outDir, "meta.json"), JSON.stringify({ ok: true }), "utf-8");
        console.log(`  ✓ ${ex.slug} — WASM ready`);
      } else {
        meta[ex.slug] = { ok: false, error: `.wasm not found at ${wasmPath}` };
        console.error(`  ✗ ${ex.slug} — .wasm not found`);
      }
    }

  } catch (err) {
    const stderr = (typeof err.stderr === 'string' ? err.stderr : (err.stderr || err.stdout || Buffer.alloc(0)).toString());
    const stdout = (err.stdout || Buffer.alloc(0)).toString();
    const allOutput = stderr || stdout || err.message || "";
    console.error(`  ✗ workspace build failed`);
    const errorLines = allOutput.split("\n").filter(l => l.includes("error[") || l.includes("Error") || l.includes("compile_error")).slice(-10).join("\n");

    // Try to attribute errors per-crate
    for (const ex of items) {
      const outDir = path.join(WASM_OUT, ex.slug);
      const wasmName = `example_${ex.slug.replace(/-/g, "_")}`;
      const wasmPath = path.join(CARGO_TARGET_DIR, "wasm32-unknown-unknown", "release", `${wasmName}.wasm`);

      if (fs.existsSync(wasmPath)) {
        // Compiled despite overall failure (could be another crate that failed)
        execSync(`wasm-bindgen --out-dir "${outDir}" --target no-modules --no-typescript "${wasmPath}" 2>&1`, { stdio: "pipe", timeout: 30000 });
        writeHtmlShell(outDir, ex.slug);
        meta[ex.slug] = { ok: true };
        fs.writeFileSync(path.join(outDir, "meta.json"), JSON.stringify({ ok: true }), "utf-8");
        console.log(`  ✓ ${ex.slug} — WASM ready`);
      } else {
        const crateErrors = errorLines || allOutput.slice(0, 2500);
        meta[ex.slug] = { ok: false, error: crateErrors };
        fs.writeFileSync(path.join(outDir, "meta.json"), JSON.stringify(meta[ex.slug]), "utf-8");
        console.error(`  ✗ ${ex.slug}`);
      }
    }
  }

  // Clean up workspace
  if (fs.existsSync(workspaceDir)) fs.rmSync(workspaceDir, { recursive: true, force: true });

  return meta;
}

// ── Step 3: write build metadata into the TS module ──────────────────────────

function writeBuildMeta(metadata) {
  const code = fs.readFileSync(OUT_TS, "utf-8");

  // Read HTML shell content for each compiled example
  for (const [slug, meta] of Object.entries(metadata)) {
    if (meta.ok) {
      const htmlPath = path.join(WASM_OUT, slug, "index.html");
      if (fs.existsSync(htmlPath)) {
        meta.html = fs.readFileSync(htmlPath, "utf-8");
      }
    }
  }

  const metaJSON = JSON.stringify(metadata, null, 2);
  const updated =
    code +
    `\n\nexport interface WasmMeta { ok: boolean; error?: string; html?: string }\nexport const wasmBuildMeta: Record<string, WasmMeta> = ${metaJSON};\n`;
  fs.writeFileSync(OUT_TS, updated, "utf-8");
}

// ── Main ─────────────────────────────────────────────────────────────────────

function main() {
  console.log("[build-examples] collecting sources…");
  const items = collectSources();
  const stripped = items.map(({ file, ...rest }) => rest);
  writeTsModule(stripped);
  console.log(`  TS → ${items.length} examples`);

  console.log("[build-examples] WASM compilation…");
  const meta = compileWasm(items);
  writeBuildMeta(meta);

  const ok = Object.values(meta).filter((m) => m.ok).length;
  const fail = Object.values(meta).filter((m) => !m.ok).length;
  console.log(`[build-examples] done — ${ok} compiled, ${fail} failed`);
}

main();
