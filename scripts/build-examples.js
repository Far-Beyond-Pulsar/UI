/**
 * build-examples.js
 *
 * 1. Reads all .rs files from examples/
 * 2. Generates lib/generated-examples.ts for the code viewer
 * 3. Compiles each example to wasm32 via wasm-pack
 * 4. Generates index.html shells for live preview
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const EXAMPLES_DIR = path.join(ROOT, "examples");
const OUT_TS = path.join(ROOT, "lib", "generated-examples.ts");
const WASM_OUT = path.join(ROOT, "public", "wasm");

// ── Helpers ──────────────────────────────────────────────────────────────────

function slug(name) {
  return name.replace(/\.rs$/, "").replace(/_/g, "-");
}
function title(name) {
  return name.replace(/\.rs$/, "").replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}
function parseDescription(source) {
  const lines = source.split("\n");
  const docs = [];
  let inBlock = false;
  for (const line of lines) {
    const t = line.trim();
    if (t.startsWith("//!")) {
      inBlock = true;
      const text = t.replace("//!", "").trim();
      if (text && !text.startsWith("!")) docs.push(text);
    } else if (inBlock) break;
  }
  return docs.join(" ");
}

// ── Ensure wasm-pack is installed ───────────────────────────────────────────

function ensureWasmPack() {
  try {
    execSync("wasm-pack --version", { stdio: "pipe" });
    console.log("  wasm-pack: OK");
  } catch {
    console.log("  installing wasm-pack…");
    execSync("cargo install wasm-pack", { stdio: "inherit", timeout: 300000 });
  }
}

// ── Step 1: collect sources + write TS module ───────────────────────────────

function collectSources() {
  return fs
    .readdirSync(EXAMPLES_DIR)
    .filter((f) => f.endsWith(".rs") && f !== "mod.rs")
    .map((file) => {
      const source = fs.readFileSync(path.join(EXAMPLES_DIR, file), "utf-8");
      return { slug: slug(file), title: title(file), description: parseDescription(source) || `${title(file)} example`, file, source };
    });
}

function writeTsModule(items) {
  const code =
    "// Generated by scripts/build-examples.js — do not edit manually\n" +
    "export interface Example { slug: string; title: string; description: string; source: string; }\n" +
    `export const examples: Example[] = ${JSON.stringify(items, null, 2)};\n`;
  fs.writeFileSync(OUT_TS, code, "utf-8");
}

// ── Step 2: compile each example with wasm-pack ─────────────────────────────

function compileWasm(items) {
  const meta = {};

  for (const ex of items) {
    const outDir = path.join(WASM_OUT, ex.slug);
    const crateDir = path.join(WASM_OUT, ex.slug, "_crate");
    const crateSrc = path.join(crateDir, "src");

    fs.mkdirSync(crateSrc, { recursive: true });

    // Cargo.toml
    fs.writeFileSync(path.join(crateDir, "Cargo.toml"), [
      '[package]',
      `name = "wgpui-${ex.slug}"`,
      'version = "0.1.0"',
      'edition = "2021"',
      '',
      '[package.metadata.wasm-pack.profile.release]',
      'wasm-opt = false',
      '',
      '[lib]',
      'crate-type = ["cdylib"]',
      '',
      '[dependencies]',
      'gpui-ce = { path = "D:/GitHub/WGPUI" }',
      'wasm-bindgen = "0.2"',
      'console_error_panic_hook = "0.1"',
      'getrandom = { version = "0.4", features = ["wasm_js"] }',
      'web-sys = { version = "0.3", features = ["Window", "Performance"] }',
    ].join("\n"), "utf-8");

    // lib.rs wrapper
    let cleaned = ex.source.replace(/^\/\/!.*$/gm, "").replace(/\n{3,}/g, "\n\n");
    let body = cleaned.replace(
      /^(pub )?fn main\(\s*\)\s*\{/m,
      '#[wasm_bindgen(start)]\npub fn start() {\n    console_error_panic_hook::set_once();');
    const libContent = 'use wasm_bindgen::prelude::*;\n\n' + body;
    fs.writeFileSync(path.join(crateSrc, "lib.rs"), libContent, "utf-8");
    console.log(`    source: ${libContent.length} bytes, ${ex.source.length} bytes original`);

    // Build with wasm-pack
    const wasmName = `wgpui_${ex.slug.replace(/-/g, "_")}`;
    console.log(`  building ${ex.slug}…`);

    // Clean any stale target cache from previous builds
    const crateTarget = path.join(crateDir, "target");
    if (fs.existsSync(crateTarget)) fs.rmSync(crateTarget, { recursive: true, force: true });

    let buildOk = false;
    try {
      execSync(
        `wasm-pack build --target web --out-dir "${outDir}" --out-name "${wasmName}" "${crateDir}"`,
        { stdio: "pipe", timeout: 600000, env: { ...process.env, CARGO_TARGET_DIR: path.join(ROOT, "target", "wasm-cache") } }
      );
      buildOk = true;
    } catch (err) {
      // wasm-opt crashes on Windows but the WASM is already built.
      // Check if the WASM file exists despite the error.
      const wasmPath = path.join(outDir, `${wasmName}_bg.wasm`);
      if (fs.existsSync(wasmPath) && fs.statSync(wasmPath).size > 100000) {
        buildOk = true;
        console.log(`  ${ex.slug} — WASM built (wasm-opt skipped)`);
      } else {
        const stderr = (err.stderr || err.stdout || err.message || "").toString();
        const lines = stderr.split("\n").filter(l => l.includes("error") || l.includes("Error")).slice(-5).join("\n");
        meta[ex.slug] = { ok: false, error: lines || stderr.slice(0, 2000) };
        console.error(`  ✗ ${ex.slug}`);
      }
    }

    if (buildOk) {
      writeHtmlShell(outDir, wasmName, ex.slug);
      meta[ex.slug] = { ok: true };
      console.log(`  ✓ ${ex.slug}`);
    }

    // Clean up crate dir (keep for debugging)
    // if (fs.existsSync(crateDir)) fs.rmSync(crateDir, { recursive: true, force: true });
  }

  return meta;
}

// ── HTML shell ──────────────────────────────────────────────────────────────

function writeHtmlShell(outDir, wasmName, slug) {
  const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    html, body { width: 100%; height: 100%; overflow: hidden; background: #000; }
    canvas { display: block; width: 100%; height: 100%; }
  </style>
</head>
<body>
  <script type="module">
    import init from "./${wasmName}.js";
    try {
      await init();
    } catch (e) {
      if (String(e).includes("exceptions for control flow")) {
        console.log("WASM running (winit control flow)");
      } else {
        document.body.innerHTML = '<div style="color:#ef4444;padding:2rem;font-family:monospace;font-size:14px">Failed: ' + e.message + '<\/div>';
      }
    }
  </script>
</body>
</html>`;
  fs.writeFileSync(path.join(outDir, "index.html"), html, "utf-8");
}

// ── Step 3: write build metadata ────────────────────────────────────────────

function writeBuildMeta(metadata) {
  const code = fs.readFileSync(OUT_TS, "utf-8");
  const metaJSON = JSON.stringify(metadata, null, 2);
  const updated = code + `\n\nexport interface WasmMeta { ok: boolean; error?: string }\nexport const wasmBuildMeta: Record<string, WasmMeta> = ${metaJSON};\n`;
  fs.writeFileSync(OUT_TS, updated, "utf-8");
}

// ── Main ─────────────────────────────────────────────────────────────────────

function main() {
  console.log("[build-examples] collecting sources…");
  const items = collectSources();
  writeTsModule(items.map(({ file, ...rest }) => rest));
  console.log(`  TS → ${items.length} examples`);

  console.log("[build-examples] checking wasm-pack…");
  ensureWasmPack();

  console.log("[build-examples] WASM compilation…");
  const meta = compileWasm(items);
  writeBuildMeta(meta);

  const ok = Object.values(meta).filter((m) => m.ok).length;
  const fail = Object.values(meta).filter((m) => !m.ok).length;
  console.log(`[build-examples] done — ${ok} compiled, ${fail} failed`);
}

main();
